import numpy as np
a = np.array([10, 20, 30], dtype=np.int64)
print("Integer Array:", a)
print("Data Type:", a.dtype)
b = np.array([10.5, 20.5, 30.5], dtype=np.float64)
print(" Float Array:", b)
print("Data Type:", b.dtype)
c = np.array([True, False, True])
print(" Boolean Array:", c)
print("Data Type:", c.dtype)
d = np.array(["Apple", "Banana", "Mango"])
print(" String Array:", d)
print("Data Type:", d.dtype)
one_d = np.array([1, 2, 3, 4, 5])
print(" 1-D Array:", one_d)
print("Shape:", one_d.shape)
two_d = np.array([[1, 2, 3],
                  [4, 5, 6]])
print(" 2-D Array:")
print(two_d)
print("Shape:", two_d.shape)
three_d = np.array([[[1, 2], [3, 4]],
                    [[5, 6], [7, 8]]])
print(" 3-D Array:")
print(three_d)
print("Shape:", three_d.shape)
